// Renders the sprites of the .px.js files here into Dart pixel grids for PixelPatternPainter.
//   node --disable-warning=ExperimentalWarning art_src/pxl/export_dart.mjs
// Writes lib/components/home_button_art.dart (buttons.px.js) and
// lib/components/play/toy_chest_art.dart (toychest.px.js). Each grid's colours
// get their own one-character keys; '.' is see-through.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { loadProject } from "../../.claude/skills/pxl-pixel-art/src/index.ts";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");

const KEYS = "XabcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWYZ0123456789";
const hex = (n) => n.toString(16).toUpperCase().padStart(2, "0");

function grid(project, name) {
  const img = project.image(name);
  const keys = new Map();
  const rows = [];
  for (let y = 0; y < img.h; y++) {
    let row = "";
    for (let x = 0; x < img.w; x++) {
      const px = img.data[y * img.w + x] >>> 0;
      const a = px & 0xff;
      if (a === 0) { row += "."; continue; }
      const argb = `${hex(a)}${hex((px >>> 24) & 0xff)}${hex((px >>> 16) & 0xff)}${hex((px >>> 8) & 0xff)}`;
      if (!keys.has(argb)) {
        if (keys.size >= KEYS.length) throw new Error(`${name}: out of keys`);
        keys.set(argb, KEYS[keys.size]);
      }
      row += keys.get(argb);
    }
    rows.push(row);
  }
  return { rows, keys, w: img.w, h: img.h };
}

function dart(project, constName, name, doc) {
  const { rows, keys, w, h } = grid(project, name);
  const inks = [...keys].map(([argb, k]) => `  '${k}': Color(0x${argb}),`).join("\n");
  return `${doc}
const Map<String, Color> ${constName}Inks = {
${inks}
};

/// ${w}x${h} cells.
const List<String> ${constName}Rows = [
${rows.map((r) => `  '${r}',`).join("\n")}
];
`;
}

function emit(px, outPath, items) {
  const project = loadProject(join(here, px));
  const out = `// GENERATED by art_src/pxl/export_dart.mjs from art_src/pxl/${px}.
// Edit the .px.js and run the exporter; do not edit this file by hand.
library;

import 'package:flutter/painting.dart';

${items.map(([constName, name, doc]) => dart(project, constName, name, doc)).join("\n")}`;
  writeFileSync(join(root, outPath), out);
  console.log(`wrote ${outPath}`);
}

