"""Measure how wide each accessory's art actually is, for the sprite to clamp.

The accessory pieces were drawn on the cat, whose head sits near the middle of
the canvas, and some of them are nearly as wide as the canvas itself -- the
wizard hat spans x 20..202 of a canvas that runs -20..202. A pet whose head is
off to one side has to move a hat sideways to wear it, and the widest pieces
then run off the edge and are cut.

So the sprite clamps: a piece is moved as far as the pet's offset asks, or as
far as the canvas allows, whichever is less. A wide hat has a lot of slack over
a small head -- being 20 units off centre still covers it -- so pulling it back
costs much less than slicing its brim off. Narrow pieces are not clamped at all
and land exactly where the pet wants them.

Writes `lib/constants/accessory_extents.dart`. Re-run after adding or redrawing
an accessory; `flutter test` fails if a piece is missing from it.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SVGS = os.path.join(HERE, '..', 'assets', 'svgs')
OUT = os.path.join(HERE, '..', 'lib', 'constants', 'accessory_extents.dart')


def x_extent(path):
    """Leftmost and rightmost x the art paints, in canvas units."""
    text = open(path, encoding='utf-8').read()
    xs = []
    for d in re.findall(r'\sd="([^"]+)"', text):
        # The art is axis-aligned: every x comes from an M, L or H.
        for cmd, val in re.findall(r'([MLH])\s*(-?[\d.]+)', d):
            xs.append(float(val))
    for m in re.finditer(r'<rect[^>]*?x="(-?[\d.]+)"[^>]*?width="([\d.]+)"', text):
        x = float(m.group(1))
        xs += [x, x + float(m.group(2))]
    return (min(xs), max(xs)) if xs else None


def main():
    rows = []
    for name in sorted(os.listdir(SVGS)):
        if not name.startswith('acc_') or not name.endswith('.svg'):
            continue
        if '_icon' in name:
            continue                       # cropped to its own bbox, never worn
        span = x_extent(os.path.join(SVGS, name))
        if span is None:
            continue
        rows.append((name, span[0], span[1]))

    body = ['/// Generated by `art_src/gen_acc_extents.py` -- do not hand-edit.',
            '///',
            '/// Asset file name -> the leftmost and rightmost x its art paints, in',
            '/// canvas art units. The sprite uses this to keep a piece it is moving',
            '/// sideways from running off the canvas and being cut; see',
            '/// `_AccessoryPlacement` in character_sprite.dart.',
            'library;',
            '',
            'class AccessoryExtent {',
            '  final double left;',
            '  final double right;',
            '  const AccessoryExtent(this.left, this.right);',
            '}',
            '',
            'const Map<String, AccessoryExtent> kAccessoryExtents = {']
    for name, lo, hi in rows:
        body.append("  'assets/svgs/%s': AccessoryExtent(%g, %g)," % (name, lo, hi))
    body += ['};', '']
    open(OUT, 'w', encoding='utf-8').write('\n'.join(body))
    print('wrote %s with %d pieces' % (OUT, len(rows)))
    for name, lo, hi in rows:
        print('  %-26s %6.0f .. %6.0f' % (name, lo, hi))


if __name__ == '__main__':
    main()
