/// The coat [type] starts in: the colour it was drawn in, or the house grey
/// for a pet that was drawn grey.
String naturalCoatFor(String type) =>
    _kReworkCoats[type] ?? kNaturalCoats[type] ?? kDefaultBodyColor;

/// Id of the swatch standing for "the coat as drawn".
const String kNaturalCoatSwatchId = 'coat_natural';

/// The coat picker for [type]: its own drawn coat first, then the shared
/// palette. The drawn coat is dropped when a palette swatch already paints it,
/// so no colour shows twice.
List<PetSwatch> bodySwatchesFor(String type) {
  final natural = naturalCoatFor(type);
  return [
    if (swatchByHex(kAllBodySwatches, natural) == null)
      PetSwatch(kNaturalCoatSwatchId, 'Original', natural),
    ...kAllBodySwatches,
  ];
}

/// The drawn tones to paint [type] with while it wears [bodyColor], or null
/// when that is not its natural coat and the derived tones apply.
NaturalTones? naturalTonesFor(String type, String bodyColor) {
  if (bodyColor.toLowerCase() != naturalCoatFor(type).toLowerCase()) {
    return null;
  }
  return kNaturalTones[type] ?? const NaturalTones();
}

