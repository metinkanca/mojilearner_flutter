/// The pets a player can live with, in rank order.
///
/// One list rather than a copy per screen. It was four copies of
/// `{'dog', 'cat', 'bird'}` — the provider's validity check, the provider's
/// load-time repair, the pet-changer's carousel and the opening's — and a pet
/// added to three of the four is a pet that can be chosen and then silently
/// reset to the cat on the next launch.
///
/// The order is the rank the carousels show left to right, and it is also the
/// order they are met in at first launch, so a pet is always where it was left.
/// The first three are the original set and keep their places; the cat is
/// second because it is what a new player starts with.
