/// The colours a pet was actually drawn in, beyond its main coat.
///
/// The generators flatten every master to the house tones so one asset can be
/// repainted any colour, and a repaint derives the shade and highlight from
/// the coat by formula. That is right for a lilac fox and wrong for the fox:
/// its drawn shade is not `darken(orange)`. So while a pet wears its natural
/// coat, these drawn tones are put back instead, and it looks exactly like
/// the art it was made from. Null keeps the derived tone.
class NaturalTones {
  final String? shade;
  final String? light;

  /// The beak as drawn, for a pet whose beak otherwise follows the coat.
  final String? beak;

  const NaturalTones({this.shade, this.light, this.beak});
}

