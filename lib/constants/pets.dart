/// The pet a player starts with, and what an unrecognised saved type falls
/// back to.
const String kDefaultPetType = 'cat';

/// Whether [type] is a pet this build ships art for.
bool isKnownPetType(String type) => kPetTypes.contains(type);

/// The pets every player has from the start: the original three, and the only
/// ones the opening offers. Every other pet in [kPetTypes] is bought.
const List<String> kStarterPetTypes = ['dog', 'cat', 'bird'];

/// What each of the other pets costs.
///
/// One price for all of them, set against the economy the owner signed off on
/// (2026-09-19): with the 27 pets at 300 on top of the rest of the catalogue,
/// a regular player owns everything in about four months, a keen one in under
/// three, and a player saving only for pets gets a new one about every four
/// days. See `test/unit/economy_curve_test.dart` for the model.
const int kPetPrice = 300;

bool isStarterPet(String type) => kStarterPetTypes.contains(type);

/// The coins [type] costs, or null for a starter, which is never for sale.
int? petPrice(String type) => isStarterPet(type) ? null : kPetPrice;

/// What a bought pet is recorded as in the unlocked set it shares with bought
/// accessories, colours and scenes. Prefixed so a pet can never collide with
/// an item id.
String petUnlockId(String type) => 'pet_$type';

